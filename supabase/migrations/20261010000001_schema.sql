create extension if not exists pgcrypto;

-- Tự cập nhật updated_at
create or replace function public.touch_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;

-- ---------------------------------------------------------------- Cấu hình
-- key 'store': thông tin cửa hàng, phí ship, phí lắp đặt... (đọc công khai)
create table public.settings (
  key        text primary key,
  value      jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

-- ---------------------------------------------------------------- Danh mục
create table public.categories (
  id         text primary key,                 -- slug: may-lanh, tu-lanh...
  name       text not null,
  short      text not null,
  icon       text not null default 'box',
  art        text,
  subs       jsonb not null default '[]'::jsonb,   -- [{id, name}]
  filters    jsonb not null default '[]'::jsonb,   -- [{key, label, options[]}]
  sort       int  not null default 0,
  active     boolean not null default true,
  updated_at timestamptz not null default now()
);

create table public.brands (
  id         text primary key,
  name       text not null,
  origin     text,
  color      text,
  sort       int not null default 0,
  active     boolean not null default true,
  updated_at timestamptz not null default now()
);

-- ---------------------------------------------------------------- Sản phẩm
create table public.products (
  id           bigint generated by default as identity (start with 5000) primary key,
  sku          text not null unique,
  slug         text not null unique,
  name         text not null,
  cat          text not null references public.categories(id) on update cascade,
  sub          text,
  brand        text not null references public.brands(id) on update cascade,
  price        bigint not null check (price >= 0),
  old_price    bigint check (old_price is null or old_price >= 0),
  rating       numeric(2,1) not null default 5 check (rating between 0 and 5),
  reviews      int not null default 0,
  sold         int not null default 0,
  stock        int not null default 0 check (stock >= 0),
  badges       text[] not null default '{}',
  gift         text,
  installment  boolean not null default false,
  free_install boolean not null default false,
  flash_sale   boolean not null default false,
  attrs        jsonb not null default '{}'::jsonb,  -- giá trị dùng cho bộ lọc
  specs        jsonb not null default '{}'::jsonb,  -- bảng thông số kỹ thuật
  highlights   text[] not null default '{}',
  short        text,
  warranty     text,
  art          jsonb not null default '{"type":"generic","color":"white"}'::jsonb,
  images       text[] not null default '{art:0,art:1,art:2}',  -- URL ảnh thật hoặc art:N
  active       boolean not null default true,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create index products_cat_idx on public.products (cat, sub) where active;
create index products_brand_idx on public.products (brand) where active;
create index products_attrs_idx on public.products using gin (attrs);

-- ---------------------------------------------------------------- Nội dung
create table public.stores (
  id         int generated by default as identity primary key,
  name       text not null,
  city       text not null,
  address    text not null,
  phone      text,
  hours      text,
  map        text,
  sort       int not null default 0,
  active     boolean not null default true,
  updated_at timestamptz not null default now()
);

create table public.posts (
  slug       text primary key,
  title      text not null,
  cat        text,
  date       date not null default current_date,
  author     text,
  art        text default 'ac',
  excerpt    text,
  content    text,
  published  boolean not null default true,
  updated_at timestamptz not null default now()
);

create table public.banners (
  id         int generated by default as identity primary key,
  title      text not null,
  sub        text,
  cta        text,
  href       text,
  theme      text default 'blue',
  art        text default 'ac',
  sort       int not null default 0,
  active     boolean not null default true,
  updated_at timestamptz not null default now()
);

create table public.services (
  id          text primary key,
  name        text not null,
  price       bigint not null default 0,
  unit        text,
  icon        text,
  description text,
  sort        int not null default 0,
  active      boolean not null default true,
  updated_at  timestamptz not null default now()
);

create table public.policies (
  key        text primary key,
  title      text not null,
  body       text not null,
  sort       int not null default 0,
  updated_at timestamptz not null default now()
);

-- ---------------------------------------------------------------- Khuyến mãi
create table public.coupons (
  code        text primary key check (code = upper(code)),
  type        text not null check (type in ('percent', 'fixed', 'ship')),
  value       bigint not null default 0 check (value >= 0),
  max         bigint,                       -- mức giảm tối đa (percent)
  min         bigint not null default 0,    -- giá trị đơn tối thiểu
  description text,
  is_public   boolean not null default true, -- hiện gợi ý ở giỏ hàng
  active      boolean not null default true,
  starts_at   timestamptz,
  ends_at     timestamptz,
  usage_limit int,
  used_count  int not null default 0,
  updated_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------- Khách hàng
-- Mỗi tài khoản Supabase Auth có 1 profile (tạo tự động bằng trigger)
create table public.profiles (
  id         uuid primary key references auth.users(id) on delete cascade,
  name       text not null default '',
  phone      text unique,
  email      text,
  addresses  jsonb not null default '[]'::jsonb,
  role       text not null default 'customer' check (role in ('customer', 'staff', 'admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ---------------------------------------------------------------- Đơn hàng
create table public.orders (
  id           bigint generated always as identity primary key,
  code         text not null unique,
  user_id      uuid references auth.users(id) on delete set null,
  status       text not null default 'pending'
               check (status in ('pending', 'confirmed', 'shipping', 'installing', 'done', 'cancelled')),
  phone        text not null,                -- tách riêng để tra cứu đơn
  customer     jsonb not null,               -- {gender, name, phone, email}
  shipping     jsonb not null,               -- {method, province, district, address, date, slot | store}
  payment      text not null check (payment in ('cod', 'bank', 'card', 'wallet', 'installment')),
  payment_status text not null default 'unpaid' check (payment_status in ('unpaid', 'paid', 'refunded')),
  invoice      jsonb,                        -- {company, taxCode, address, email}
  note         text,
  subtotal     bigint not null,
  install_fee  bigint not null default 0,
  shipping_fee bigint not null default 0,
  discount     bigint not null default 0,
  coupon       text,
  total        bigint not null,
  staff_note   text,                         -- ghi chú nội bộ (admin)
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create index orders_phone_idx on public.orders (phone);
create index orders_user_idx on public.orders (user_id);
create index orders_status_idx on public.orders (status, created_at desc);

create table public.order_items (
  id         bigint generated always as identity primary key,
  order_id   bigint not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  sku        text,
  name       text not null,
  price      bigint not null,
  qty        int not null check (qty between 1 and 99),
  install    boolean not null default false
);
create index order_items_order_idx on public.order_items (order_id);

-- Lịch sử trạng thái (timeline tra cứu đơn, audit cho admin)
create table public.order_status_history (
  id         bigint generated always as identity primary key,
  order_id   bigint not null references public.orders(id) on delete cascade,
  status     text not null,
  note       text,
  created_by uuid,
  created_at timestamptz not null default now()
);
create index osh_order_idx on public.order_status_history (order_id, created_at);

-- ---------------------------------------------------------------- Đánh giá
create table public.reviews (
  id         bigint generated always as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  user_id    uuid references auth.users(id) on delete set null,
  name       text not null check (length(name) between 1 and 100),
  phone      text,
  rating     int not null check (rating between 1 and 5),
  text       text not null check (length(text) between 1 and 2000),
  status     text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  verified   boolean not null default false,
  created_at timestamptz not null default now()
);
create index reviews_product_idx on public.reviews (product_id, status);

-- ---------------------------------------------------------------- Lead / CRM
-- Liên hệ, đặt lịch dịch vụ, báo giá dự án B2B, đăng ký nhận tin
create table public.leads (
  id          bigint generated always as identity primary key,
  code        text not null unique default ('L' || to_char(now(), 'YYMMDD') || lpad((floor(random() * 100000))::int::text, 5, '0')),
  type        text not null check (type in ('contact', 'service', 'b2b-quote', 'newsletter')),
  name        text,
  phone       text,
  email       text,
  company     text,
  data        jsonb not null default '{}'::jsonb,  -- toàn bộ trường của form
  status      text not null default 'new' check (status in ('new', 'contacted', 'quoted', 'won', 'lost', 'spam')),
  assigned_to uuid references auth.users(id) on delete set null,
  staff_note  text,
  source_url  text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index leads_status_idx on public.leads (status, created_at desc);
create index leads_type_idx on public.leads (type, created_at desc);

-- ---------------------------------------------------------------- Trigger updated_at
do $$
declare t text;
begin
  foreach t in array array['settings','categories','brands','products','stores','posts','banners','services',
                           'policies','coupons','profiles','orders','leads']
  loop
    execute format('create trigger %I_touch before update on public.%I for each row execute function public.touch_updated_at()', t, t);
  end loop;
end $$;
