import assert from 'node:assert/strict';
import { blockExternal, chromium, pagesServer } from './lib.mjs';

const { server, base } = await pagesServer(process.cwd());
let browser;
try {
  browser = await chromium();
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await blockExternal(context);
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const admin = `${base}admin/index.html`;
  await page.goto(`${admin}#/coupons/new`);
  await page.click('#demo-enter');
  await page.waitForSelector('#coupon-overview');
  const initial = await page.inputValue('[name=code]');
  assert.match(initial, /^[A-Z0-9]{12}$/);
  await page.click('#coupon-generate');
  assert.notEqual(await page.inputValue('[name=code]'), initial);
  await page.fill('[name=code]', 'scoped10');
  await page.fill('[name=value]', '10');
  await page.fill('[name=max]', '500000');
  await page.check('[name=scope][value=products]');
  await page.fill('#coupon-product-search', 'DT1001');
  await page.check('[data-pick="1001"]');
  await page.check('[name=condition_type][value=eligible_qty]');
  await page.fill('[name=condition_value]', '2');
  await page.check('#coupon-limit-toggle');
  await page.fill('[name=usage_limit]', '5');
  await page.check('[name=once_per_customer]');
  await page.uncheck('[name=is_public]');
  await page.fill('[name=description]', 'Giảm cho đúng sản phẩm đã chọn');
  assert.ok((await page.locator('#coupon-overview').innerText()).includes('SCOPED10'));
  await page.click('#save');
  await page.waitForURL('**#/coupons/SCOPED10');
  await page.waitForSelector('#coupon-overview');
  const saved = await page.evaluate(() => AD.db.get('coupons', 'SCOPED10'));
  assert.deepEqual(saved.product_ids, [1001]);
  assert.equal(saved.condition_type, 'eligible_qty');
  assert.equal(saved.usage_limit, 5);
  assert.equal(saved.once_per_customer, true);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.reload();
  await page.waitForSelector('#coupon-overview');
  assert.equal(await page.locator('[data-pick="1001"]').isChecked(), true);
  await page.locator('a', { hasText: 'Sao chép khuyến mãi' }).click();
  await page.waitForSelector('#coupon-generate');
  assert.notEqual(await page.inputValue('[name=code]'), 'SCOPED10');
  assert.equal(await page.locator('[data-pick="1001"]').isChecked(), true);
  assert.equal(await page.inputValue('[name=condition_value]'), '2');

  await page.goto(`${base}frontend/san-pham.html?id=1001`);
  await page.waitForSelector('#qty');
  await page.locator('.buy-btns [data-action=add-cart]').click();
  await page.goto(`${base}frontend/gio-hang.html`);
  await page.waitForSelector('.cart-item');
  assert.equal(await page.locator('[data-code=SCOPED10]').count(), 0, 'private coupon not advertised');
  let result = await page.evaluate(() => DT.store.applyCoupon('SCOPED10', '0955334400'));
  assert.equal(result.ok, false, 'minimum eligible quantity required');
  await page.evaluate(() => { DT.store.addToCart(1001, 1); DT.store.addToCart(1002, 1); });
  result = await page.evaluate(() => DT.store.applyCoupon('SCOPED10', '0955334400'));
  assert.equal(result.ok, true);
  const totals = await page.evaluate(() => DT.store.totals('0955334400'));
  const price = await page.evaluate(() => DT.api.productById(1001).price);
  assert.equal(totals.discount, Math.min(Math.floor(price * 2 / 10), 500000));
  // Checkout accepts manual codes, including private and phone-restricted codes.
  await page.goto(`${base}frontend/thanh-toan.html`);
  await page.waitForSelector('#co-form');
  await page.fill('[name=name]', 'Khách Mã Riêng');
  await page.fill('[name=phone]', '0955334400');
  await page.fill('[name=province]', 'TP. Hồ Chí Minh').catch(() => page.selectOption('[name=province]', 'TP. Hồ Chí Minh'));
  await page.fill('[name=district]', 'Quận 7');
  await page.fill('[name=address]', '123 Nguyễn Thị Thập');
  await page.fill('#co-coupon-code', 'SCOPED10');
  await page.click('#co-apply-coupon');
  await page.waitForFunction(() => DT.store.totals('0955334400').discount > 0);
  await page.click('#co-form button[type=submit]');
  await page.waitForURL(/dat-hang-thanh-cong/);
  const code = new URL(page.url()).searchParams.get('code');
  const order = await page.evaluate(() => DT.store.get().orders[0]);
  assert.equal(order.coupon, 'SCOPED10');
  assert.equal(order.discount, totals.discount);
  await page.goto(`${base}frontend/san-pham.html?id=1001`);
  await page.waitForSelector('#qty');
  await page.fill('#qty', '2');
  await page.locator('.buy-btns [data-action=add-cart]').click();
  result = await page.evaluate(() => DT.store.applyCoupon('SCOPED10', '0955334400'));
  assert.equal(result.ok, false, 'once per phone enforced');
  await page.evaluate((code) => DT.store.cancelOrder(code, '0955334400'), code);
  result = await page.evaluate(() => DT.store.applyCoupon('SCOPED10', '0955334400'));
  assert.equal(result.ok, true, 'cancellation releases usage');
  await page.goto(`${admin}#/coupons/SCOPED10`);
  await page.waitForSelector('#coupon-overview');
  assert.equal((await page.evaluate(() => AD.db.get('coupons', 'SCOPED10'))).used_count, 0);
  await page.click('#coupon-toggle');
  await page.waitForFunction(async () => (await AD.db.get('coupons', 'SCOPED10')).active === false);
  await page.reload();
  await page.waitForSelector('#coupon-toggle');
  assert.ok((await page.locator('#coupon-toggle').innerText()).includes('Tiếp tục'));
  assert.deepEqual(errors, []);
  console.log('PASS: coupon layout, random/manual code, copy, scope, private code, conditions, caps, checkout, once/customer, cancellation, pause, persistence, mobile');
} finally {
  await browser?.close();
  await new Promise((resolve) => server.close(resolve));
}
