import assert from 'node:assert/strict';
import { blockExternal, chromium, pagesServer } from './lib.mjs';

const { server, base } = await pagesServer(process.cwd());
let browser;
try {
  browser = await chromium();
  const context = await browser.newContext({ viewport: { width: 1366, height: 900 } });
  await blockExternal(context);
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const admin = `${base}admin/index.html`;
  const product = `${base}frontend/san-pham.html?id=1071`;
  await page.goto(`${admin}#/products/1071`);
  await page.click('#demo-enter');
  await page.waitForSelector('[data-kv=options]');
  await page.locator('[data-kv=options] [data-k]').first().fill('Kích thước');
  await page.locator('[data-kv=options] [data-v]').first().fill('S, M, L, M');
  await page.click('[data-kv-add=options]');
  await page.locator('[data-kv=options] [data-k]').last().fill('Model');
  await page.locator('[data-kv=options] [data-v]').last().fill('R32; R410A');
  await page.click('#save');
  await page.waitForFunction(async () => (await AD.db.get('products', 1071)).options.Model === 'R32; R410A');
  await page.goto(product);
  await page.waitForSelector('.pd-option');
  assert.deepEqual(await page.locator('.pd-option-group legend').allTextContents(), ['Kích thước', 'Model']);
  assert.deepEqual(await page.locator('[data-option-group="0"] .pd-option').allTextContents(), ['S', 'M', 'L']);
  const groupBox = await page.locator('#pd-options').boundingBox();
  const qtyBox = await page.locator('.buy-row').boundingBox();
  assert.ok(groupBox.y + groupBox.height <= qtyBox.y);
  const add = page.locator('.buy-btns [data-action=add-cart]');
  await add.click();
  assert.equal((await page.evaluate(() => DT.store.get().cart)).length, 0);
  assert.equal(await page.locator('.pd-option-group.invalid').count(), 2);
  await page.click('[data-option-value="M"]');
  await add.click();
  assert.equal((await page.evaluate(() => DT.store.get().cart)).length, 0);
  await page.click('[data-option-value="R32"]');
  await page.fill('#qty', '2');
  await add.click();
  await page.waitForSelector('.modal-wrap');
  await page.evaluate(() => DT.ui.close());
  await page.fill('#qty', '1');
  await add.click();
  await page.waitForSelector('.modal-wrap');
  await page.evaluate(() => DT.ui.close());
  assert.equal((await page.evaluate(() => DT.store.get().cart))[0].qty, 3);
  await page.click('[data-option-value="L"]');
  await page.click('[data-option-value="R410A"]');
  await add.click();
  assert.equal((await page.evaluate(() => DT.store.get().cart)).length, 2);
  await page.goto(`${base}frontend/gio-hang.html`);
  await page.waitForSelector('.cart-item');
  assert.equal(await page.locator('.cart-item').count(), 2);
  assert.ok((await page.locator('.cart-item').first().innerText()).includes('Kích thước: M · Model: R32'));
  await page.locator('.cart-item').last().locator('[data-q="1"]').click();
  assert.deepEqual((await page.evaluate(() => DT.store.get().cart)).map((i) => i.qty), [3, 2]);
  await page.locator('.cart-item').last().locator('[data-remove]').click();
  assert.equal(await page.locator('.cart-item').count(), 1);
  assert.equal((await page.evaluate(() => DT.store.get().cart))[0].options.Model, 'R32');
  await page.goto(product);
  await page.click('[data-option-value="L"]');
  await page.click('[data-option-value="R410A"]');
  await page.locator('.buy-btns [data-action=buy-now]').click();
  await page.waitForURL('**/gio-hang.html');
  await page.reload();
  await page.waitForSelector('.cart-item');
  assert.equal(await page.locator('.cart-item').count(), 2);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.goto(`${base}frontend/thanh-toan.html`);
  await page.waitForSelector('#co-summary');
  assert.ok((await page.locator('#co-summary').innerText()).includes('Model: R410A'));
  await page.fill('[name=name]', 'Khách Chọn Model');
  await page.fill('[name=phone]', '0901234567');
  await page.fill('[name=province]', 'TP. Hồ Chí Minh').catch(() => page.selectOption('[name=province]', 'TP. Hồ Chí Minh'));
  await page.fill('[name=district]', 'Quận 7');
  await page.fill('[name=address]', '123 Nguyễn Thị Thập');
  await page.click('#co-form button[type=submit]');
  await page.waitForURL(/dat-hang-thanh-cong/);
  const code = new URL(page.url()).searchParams.get('code');
  await page.waitForSelector('.item-options');
  assert.ok((await page.locator('.item-options').allTextContents()).some((text) => text.includes('Model: R410A')));
  const order = await page.evaluate(() => DT.store.get().orders[0]);
  assert.equal(order.items.length, 2);
  assert.deepEqual(order.items[0].options, { 'Kích thước': 'M', Model: 'R32' });
  await page.goto(`${admin}#/orders/${code}`);
  await page.waitForSelector('.ad-table');
  assert.ok((await page.locator('.ad-table').first().innerText()).includes('Model: R410A'));
  assert.deepEqual(errors, []);
  console.log('PASS: admin options → selectors above quantity → required choices → separate cart rows → quantities/removal → checkout → order → admin');
} finally {
  await browser?.close();
  await new Promise((resolve) => server.close(resolve));
}
